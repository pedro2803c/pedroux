// Idioma: ?lang= na URL tem prioridade (funciona mesmo sem armazenamento); senão, a última escolha salva
const LANG_KEY = 'portfolio-lang';
const getLang = () => {
  const param = new URLSearchParams(location.search).get('lang');
  if (param === 'en' || param === 'pt') {
    try { localStorage.setItem(LANG_KEY, param); } catch {}
    return param;
  }
  try { return localStorage.getItem(LANG_KEY) === 'en' ? 'en' : 'pt'; } catch { return 'pt'; }
};
const lang = getLang();

const norm = s => s.replace(/\s+/g, ' ').trim();
const toEn = s => {
  const key = norm(s);
  if (!key) return null;
  if (key in EN) return EN[key];
  for (const [rx, out] of EN_PATTERNS) if (rx.test(key)) return key.replace(rx, out);
  return null;
};

const translateText = node => {
  const en = toEn(node.nodeValue);
  if (en === null || en === norm(node.nodeValue)) return;
  // preserva os espaços das pontas para não colar palavras vizinhas
  const lead = node.nodeValue.match(/^\s*/)[0], trail = node.nodeValue.match(/\s*$/)[0];
  node.nodeValue = lead + en + trail;
};
const ATTRS = ['alt', 'aria-label', 'title'];
const translateAttrs = el => ATTRS.forEach(a => {
  const v = el.getAttribute(a);
  const en = v && toEn(v);
  if (en && en !== v) el.setAttribute(a, en);
});
const translateTree = root => {
  if (root.nodeType === 3) return translateText(root);
  if (root.nodeType !== 1 || root.closest('script, style')) return;
  translateAttrs(root);
  root.querySelectorAll('*').forEach(translateAttrs);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: n => n.parentElement.closest('script, style') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT,
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(translateText);
};

if (lang === 'en') {
  document.documentElement.lang = 'en';
  const t = toEn(document.title);
  if (t) document.title = t;
  translateTree(document.body);
  // O main.js cria listas, filtros e janelas depois: traduz o que entrar ou mudar na página
  new MutationObserver(muts => {
    for (const m of muts) {
      if (m.type === 'childList') m.addedNodes.forEach(translateTree);
      else if (m.type === 'attributes') translateAttrs(m.target);
    }
  }).observe(document.body, { childList: true, subtree: true, attributes: true, attributeFilter: ATTRS });
}

// Botão PT | EN: guarda a escolha (vale para todas as páginas) e recarrega no outro idioma
document.querySelectorAll('.js-lang').forEach(btn => {
  btn.querySelector(`[data-l="${lang}"]`)?.classList.add('is-active');
  btn.setAttribute('aria-label', lang === 'en' ? 'PT/EN: Mudar para português' : 'PT/EN: Switch to English');
  btn.addEventListener('click', () => {
    const next = lang === 'en' ? 'pt' : 'en';
    try { localStorage.setItem(LANG_KEY, next); } catch {}
    const url = new URL(location.href);
    url.searchParams.set('lang', next);
    location.href = url.toString();
  });
});
